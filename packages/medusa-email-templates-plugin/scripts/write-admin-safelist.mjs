#!/usr/bin/env node
/**
 * Makes this plugin's Tailwind classes reachable by the host admin build.
 *
 * The host assembles Tailwind's `content` in `@medusajs/admin-bundler`:
 *
 *   createTailwindConfig(entry, sources, plugins)
 *     pluginExtensions = dirname(require.resolve(pluginAdminSpecifier))
 *                        + "**\/*.{js,ts,jsx,tsx}"
 *
 * For an installed plugin that specifier is the package's `./admin` subpath,
 * so the glob root is `.medusa/server/src/admin`. But the same package's
 * plugin build emits every chunk through:
 *
 *   chunkFileNames: () => `_chunks/[name]-[hash]`
 *
 * with no extension, so the glob matches nothing except the 139-byte
 * `index.js` re-export — which contains no class names. Every class this
 * plugin writes that Medusa's own components do not also use is therefore
 * dropped, silently: no error, no warning, just an unstyled element.
 *
 * This writes one real `.js` file into that glob root carrying the class
 * candidates found in the built chunks, which is what the host would have
 * scanned had the chunks been named with an extension.
 *
 * Runs after `medusa plugin:build`, because that wipes `.medusa/server`.
 * Nothing imports the generated file; it exists only to be read by Tailwind.
 * If Medusa ever adds extensions to chunk names this becomes redundant rather
 * than wrong, since the chunks would then be scanned directly.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const adminDir = join(packageRoot, '.medusa', 'server', 'src', 'admin');
const chunksDir = join(adminDir, '_chunks');
const outFile = join(adminDir, 'tailwind-safelist.js');

if (!existsSync(chunksDir)) {
  console.error(
    `[safelist] No admin chunks at ${chunksDir}. Run "medusa plugin:build" first.`,
  );
  process.exit(1);
}

/*
 * Leans permissive, but anchored on a leading utility-shaped word. Tailwind
 * silently discards a candidate that matches no theme value, so a false
 * positive costs a few bytes while a false negative is the exact silent
 * failure this script exists to prevent.
 *
 * Covers bare utilities (`flex`), variants (`hover:bg-…`), fractions
 * (`w-2/3`) and arbitrary values (`text-[0.875em]`). It deliberately does
 * *not* match a bare `[...]`, which would scoop up JavaScript subscripts and
 * template-literal fragments from the surrounding bundle and leave the
 * generated file unreadable.
 */
const CANDIDATE = /[a-z][a-z0-9]*(?:[:/-][a-z0-9[\]#%._-]+)+/g;

/** Only the chunks: reading the whole directory would include our own output. */
const tokens = new Set();

for (const entry of readdirSync(chunksDir)) {
  const contents = readFileSync(join(chunksDir, entry), 'utf8');

  for (const match of contents.match(CANDIDATE) ?? []) {
    tokens.add(match);
  }
}

const safelist = [...tokens].sort();

const banner = [
  '// Generated by scripts/write-admin-safelist.mjs — do not edit.',
  '//',
  "// The host's Tailwind pass globs this directory for *.{js,ts,jsx,tsx},",
  '// but the admin build emits its chunks without a file extension, so the',
  '// classes inside them are never seen. This file carries those class',
  '// candidates in a form the glob can match. Nothing imports it.',
  '',
].join('\n');

writeFileSync(
  outFile,
  `${banner}module.exports = ${JSON.stringify(safelist, null, 2)};\n`,
  'utf8',
);

console.log(
  `[safelist] Wrote ${safelist.length} class candidates to ${outFile.replace(packageRoot, '.')}`,
);
